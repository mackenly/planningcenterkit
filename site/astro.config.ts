import { defineConfig } from "astro/config";
import tailwindcss from "@tailwindcss/vite";
import nimbus, {
  defineConfig as defineNimbusConfig,
} from "@cloudflare/nimbus-docs";
import { tableScroll } from "@cloudflare/nimbus-docs/markdown";
import cloudflare from "@astrojs/cloudflare";

const nimbusConfig = defineNimbusConfig({
  // Pages render on request so the Worker can answer `Accept: text/markdown`
  // at every page URL and serve the remote MCP server at /mcp. Markdown
  // versions, llms.txt and the search index are still prepared at build.
  rendering: { default: "request" },
  site: "https://planningcenterkit.mackenly.com",
  title: "Planning Center Kit",
  description:
    "Documentation for @mackenly/planningcenterkit, an unofficial, fully typed, zero-dependency TypeScript client for every Planning Center API.",
  locale: "en",
  github: "https://github.com/mackenly/planningcenterkit",
  // `{path}` is the page's file relative to site/. Generated reference pages
  // have no source file to edit; the docs route leaves their edit link out.
  editPattern: "https://github.com/mackenly/planningcenterkit/edit/main/site/{path}",
  socialImageAlt: "Planning Center Kit documentation",
  agents: { mcp: true },
  sidebar: {
    items: [
      "index",
      { label: "Guides", autogenerate: { directory: "guides" }, collapsed: false },
      // Generated by scripts/generate-reference.ts (npm run docs:reference).
      { label: "Reference", autogenerate: { directory: "reference" } },
    ],
    // ~300 reference pages: each rail shows only its own section, and each
    // product's reference gets a rail of its own, so pages stay small.
    scope: "section",
    isolate: { boundaries: ["reference/*"] },
    defaultCollapsed: true,
  },
});

export default defineConfig({
  // nimbus:adapter
  output: "server",
  // `compile`: the docs have no images to resize on request, so the Worker
  // needs no Cloudflare Images binding.
  adapter: cloudflare({ prerenderEnvironment: "node", imageService: "compile" }),
  // No sessions, so the Worker needs no KV namespace.
  session: false,
  // Tailwind v4 via its Vite plugin (the integration Astro recommends for
  // Tailwind v4 — replaces the PostCSS plugin, which doesn't build under
  // Astro 7's Vite 8 bundler).
  vite: {
    plugins: [tailwindcss()],
  },
  // Hover-prefetch link targets so full-page navigations feel instant without
  // a client-side router.
  prefetch: {
    prefetchAll: true,
    defaultStrategy: "hover",
  },
  integrations: [
    nimbus(nimbusConfig, {
      rules: {
        "nimbus/frontmatter-shape": "error",
        "nimbus/internal-link": "error",
        "nimbus/description-required": "warn",
        "nimbus/single-h1": "error",
        "nimbus/heading-hierarchy": "warn",
        "nimbus/duplicate-heading-text": "warn",
        "nimbus/code-block-lang": "warn",
        "nimbus/code-block-prompt-prefix": "warn",
        "nimbus/no-self-host-url": "error",
      },
      markdown: {
        // Wrap wide tables so they scroll instead of overflowing the page
        // (styled by `.nb-table-scroll` in src/styles/prose.css).
        hastPlugins: [tableScroll()],
        // `## Install {#install}` gives a heading a fixed id. A heading that
        // ends in other `{…}` text, such as `{account_id}` in a .md file, is
        // read as attributes too; remove this to keep it as text.
        features: { headingAttributes: true },
      },
    }),
  ],
});
